def parse_appliances(spec: str) -> tuple[list, list]:
    any_groups, all_list = [], []
    for part in [p for p in spec.split("+") if p]:
        if part.startswith("!"):
            all_list.append(part[1:])
        else:
            any_groups.append(part.split("/"))
    return any_groups, all_list


def build():
    ingredients = []
    for (iid, name, unit, kcal, p, c, f, fib, kind, staple, src, extra) in ING:
        diet = {"vegan": ["veg", "vegan"], "veg": ["veg"], "egg": ["egg"], "nonveg": ["nonveg"]}[kind]
        row = {"id": iid, "name": name, "unit": unit, "per_100": {"kcal": kcal, "protein_g": p, "carbs_g": c, "fat_g": f, "fibre_g": fib},
               "diet": diet, "kind": kind, "is_staple": bool(staple), "source": src, **extra}
        if iid in LOCAL_ING:
            row["name_local"] = {"kn": LOCAL_ING[iid][0], "hi": LOCAL_ING[iid][1]}
        ingredients.append(row)
    meal_map = {"B": "breakfast", "L": "lunch", "D": "dinner", "S": "snacks"}
    recipes = []
    for (rid, name, kn, hi, meals, diet, vegan_ok, appl, minutes, serv, ings, steps) in REC:
        any_g, all_l = parse_appliances(appl)
        lines = []
        for tok in ings.split(","):
            iid, qty = tok.split()
            lines.append({"id": iid, "qty": float(qty) if "." in qty else int(qty)})
        recipes.append({"id": rid, "name": name, "name_local": {"kn": kn, "hi": hi}, "meal": [meal_map[m] for m in meals],
                        "diet": diet, "vegan_ok": bool(vegan_ok), "appliances_any": any_g, "appliances_all": all_l,
                        "time_min": minutes, "base_servings": serv, "ingredients": lines, "steps": steps,
                        "youtube_query": f"{name} recipe"})
    products, pid = [], 1
    kinds = {r["id"]: r["kind"] for r in ingredients}
    units = {r["id"]: r["unit"] for r in ingredients}
    for iid, packs in PACKS.items():
        for pk in packs:
            brand_name, size, rupees = pk[0], pk[1], pk[2]
            topup = pk[3] if len(pk) > 3 else 0
            unit = units[iid]
            label = f"{size // 1000} kg" if unit == "g" and size >= 1000 and size % 1000 == 0 else \
                    f"{size // 1000} L" if unit == "ml" and size >= 1000 and size % 1000 == 0 else \
                    f"{size} g" if unit == "g" else f"{size} ml" if unit == "ml" else f"{size} pcs"
            products.append({"id": pid, "name": f"{brand_name} {label}", "brand": brand_name.split()[0], "category": CATEGORY[iid],
                             "pack_size": size, "pack_unit": unit, "price_paise": rupees * 100, "stock": 100, "available": 1,
                             "ingredient_id": iid, "topup": topup, "diet": "vegan" if kinds[iid] == "vegan" else kinds[iid]})
